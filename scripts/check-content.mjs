#!/usr/bin/env node
/*
 * Content check: every visible text of the approved design must appear verbatim in the JSON
 * of the same page and language (spec sections 6 and 15).
 *
 * Source: local copy of the design artboards in _design/project (not in the repository).
 * Run:    npm run check:content
 * Exit 1 on any missing text. Skips with a notice when _design/ is absent (CI).
 */
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parse, ELEMENT_NODE, TEXT_NODE } from 'ultrahtml';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DESIGN = path.join(ROOT, '_design', 'project');
const CONTENT = path.join(ROOT, 'src', 'content');

if (!existsSync(DESIGN)) {
  console.log('check:content skipped: _design/project not found (design source is kept locally).');
  process.exit(0);
}

/** artboard -> [lang, page json]. Settings and contacts are searched for every page. */
const PAGES = [
  ['Main', 'en', 'home'], ['MainUk', 'uk', 'home'],
  ['EquipmentHub', 'en', 'hub'], ['EquipmentHubUk', 'uk', 'hub'],
  ['ManagedStorage', 'en', 'managed'], ['ManagedStorageUk', 'uk', 'managed'],
  ['MediaStorage', 'en', 'media'], ['MediaStorageUk', 'uk', 'media'],
  ['Contact', 'en', 'contact'], ['ContactUk', 'uk', 'contact'],
  ['Privacy', 'en', 'privacy'], ['PrivacyUk', 'uk', 'privacy'],
];

/** Texts that are layout, not copy: kept in templates on purpose. */
const IGNORE = [
  /\{\{.*\}\}/, // design-tool placeholders
  /^[·/.,:→—-]$/, // separators and punctuation
  /^\d{1,2}$/, // list numbers 01–10
  /^\d+\/\d+$/, // 1/3, 2/6 package counters in illustrations
  /^(ID \d+|R04 · S07)$/, // illustration labels without language
  /^(IT ASSET|LOGISTICS)$/, // logo wordmark
  /^IT Asset Logistics$/, // brand on the asset tag
  /^© \d{4} IT Asset Logistics$/, // footer year is generated
  /^itassetlogistics\.com$/,
  /^(EN|UA)$/,
  /^\d+\. /, // privacy headings: the number is generated, the title is checked separately
];

/** Known, approved deviations from the design (spec section 16). */
const ALLOWED = new Map([
  ['uk/privacy', ['сторінку Contact']], // corrected to «сторінку «Контакти»» per the spec
  // SEO: the lead starts with «Відповідальне зберігання…», the term clients search for
  ['uk/managed', ['Зберігання корпоративного обладнання в Україні без необхідності утримувати власний склад.']],
]);

const decode = (s) =>
  s
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ');
const norm = (s) => s.replace(/\s+/g, ' ').trim();

function designTexts(file) {
  const src = readFileSync(path.join(DESIGN, `${file}.dc.html`), 'utf8');
  const body = src.slice(src.indexOf('</helmet>') + 9, src.indexOf('</x-dc>'));
  const out = [];
  let inHeaderOrFooter = 0;
  const walk = (node) => {
    if (node.type === ELEMENT_NODE) {
      if (node.name === 'style' || node.name === 'script') return;
      // header and footer copy lives in settings; checked against settings for every page anyway
      const hf = node.name === 'header' || node.name === 'footer';
      if (hf) inHeaderOrFooter++;
      for (const a of ['aria-label', 'placeholder', 'alt']) if (node.attributes[a]) out.push(node.attributes[a]);
      for (const c of node.children ?? []) walk(c);
      if (hf) inHeaderOrFooter--;
    } else if (node.type === TEXT_NODE) {
      out.push(node.value);
    } else for (const c of node.children ?? []) walk(c);
  };
  walk(parse(body));
  // Journey stages live in the artboard script as JSON
  const js = src.match(/return (\[\{"name".*?\]);/);
  if (js) for (const s of JSON.parse(js[1])) out.push(s.name, s.title, s.status, s.text);
  return [...new Set(out.map((t) => norm(decode(t))).filter((t) => t && !IGNORE.some((re) => re.test(t))))];
}

function jsonText(file) {
  const strings = [];
  const walk = (v) => {
    if (typeof v === 'string') strings.push(v);
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  };
  walk(JSON.parse(readFileSync(file, 'utf8')));
  // strip the lightweight markdown used in long texts before comparing
  return norm(strings.join('\n').replace(/\*\*(.+?)\*\*/g, '$1').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1'));
}

let failures = 0;
for (const [artboard, lang, page] of PAGES) {
  const haystack = [
    jsonText(path.join(CONTENT, 'pages', lang, `${page}.json`)),
    jsonText(path.join(CONTENT, 'settings', `${lang}.json`)),
    jsonText(path.join(CONTENT, 'settings', 'contacts.json')),
  ].join(' \n ');
  const allowed = ALLOWED.get(`${lang}/${page}`) ?? [];
  const missing = designTexts(artboard).filter((t) => {
    if (allowed.includes(t)) return false;
    // numbering ("1. Scope", "01 — Packing") and trailing arrows are generated by templates
    const bare = t.replace(/\s*→$/, '').replace(/^\d+\.\s*/, '').replace(/^\d{2} — /, '');
    return !haystack.includes(bare);
  });
  if (missing.length) {
    failures += missing.length;
    console.log(`\n✗ ${lang}/${page}.json — ${missing.length} text(s) from ${artboard} not found:`);
    for (const m of missing) console.log(`   · ${m}`);
  } else {
    console.log(`✓ ${lang}/${page}.json matches ${artboard}`);
  }
}

if (failures) {
  console.log(`\n${failures} design text(s) missing from content JSON.`);
  process.exit(1);
}
console.log('\nAll design texts are present in the content JSON.');
